"""
archive_utils.py — Shared document archive + student register module
=====================================================================

Central archive for documents generated by portal tools, plus the
Student Register (students added on arrival, archived on exit).

Storage layout (Supabase Storage, private bucket "document-archive"):
    students/{INITIALS}/{year}/{source_tool_slug}/{uuid8}_{filename}
    {year}/{term}/{source_tool_slug}/{uuid8}_{filename}   (non-student docs)

Privacy: the document_archive table stores INITIALS ONLY. Full student
names live in the student_register table in the students/behaviour
Supabase project — the same project that already holds student names
for the Behaviour Support tool.
"""

