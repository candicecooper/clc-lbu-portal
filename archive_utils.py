def archive_document(
    *,
    source_tool: str,
    doc_type: str,
    title: str,
    file_bytes: bytes,
    filename: str,
    student_initials: str | None = None,
    term: str | None = None,
    year: int | None = None,
    tags: list[str] | None = None,
    confidential: bool = False,
    created_by: str = "unknown",
    notes: str | None = None,
) -> dict | None:
    """Upload a document to the archive. Returns the inserted record,
    or None on failure (errors are shown via st.error, never raised,
    so archiving can never break the calling tool's export flow).
    """
    try:
        client = _get_client()

        default_term, default_year = _current_term_and_year()
        term = term or default_term
        year = year or default_year

        clean_name = _safe_filename(filename)
        _ini = (student_initials or "").strip().upper()
        if _ini:
            # Student-linked documents live in that student's folder
            storage_path = (
                f"students/{_ini}/{year}/{_slugify(source_tool)}/"
                f"{uuid.uuid4().hex[:8]}_{clean_name}"
            )
        else:
            storage_path = (
                f"{year}/{_slugify(term)}/{_slugify(source_tool)}/"
                f"{uuid.uuid4().hex[:8]}_{clean_name}"
            )

        content_type = (
            mimetypes.guess_type(clean_name)[0] or "application/octet-stream"
        )

        client.storage.from_(BUCKET).upload(
            storage_path,
            file_bytes,
            {"content-type": content_type},
        )

        record = {
            "source_tool": source_tool,
            "doc_type": doc_type,
            "title": title,
            "student_initials": _ini or None,
            "term": term,
            "year": year,
            "tags": tags or [],
            "storage_path": storage_path,
            "file_name": clean_name,
            "confidential": confidential,
            "created_by": created_by,
            "notes": notes,
        }

        res = client.table(TABLE).insert(record).execute()
        return res.data[0] if res.data else None

    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not archive document: {exc}")
        return None


def fetch_archive(
    *,
    include_confidential: bool = False,
    doc_type: str | None = None,
    source_tool: str | None = None,
    term: str | None = None,
    year: int | None = None,
    student_initials: str | None = None,
    keyword: str | None = None,
    include_deleted: bool = False,
    limit: int = 200,
) -> list[dict]:
    """Query the archive with optional filters, newest first."""
    try:
        client = _get_client()
        q = client.table(TABLE).select("*")

        if not include_confidential:
            q = q.eq("confidential", False)
        if not include_deleted:
            q = q.eq("deleted", False)
        if doc_type:
            q = q.eq("doc_type", doc_type)
        if source_tool:
            q = q.eq("source_tool", source_tool)
        if term:
            q = q.eq("term", term)
        if year:
            q = q.eq("year", year)
        if student_initials:
            q = q.eq("student_initials", student_initials.strip().upper())
        if keyword:
            q = q.ilike("title", f"%{keyword.strip()}%")

        res = q.order("created_at", desc=True).limit(limit).execute()
        return res.data or []

    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not load archive: {exc}")
        return []


def download_bytes(storage_path: str) -> bytes | None:
    """Fetch a document's bytes from Supabase Storage."""
    try:
        client = _get_client()
        return client.storage.from_(BUCKET).download(storage_path)
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not download file: {exc}")
        return None


def download_link_html(file_bytes: bytes, filename: str, label: str = "⬇️ Download") -> str:
    """Base64 data-URI download link (works on iOS Safari, unlike
    st.download_button)."""
    mime = mimetypes.guess_type(filename)[0] or "application/octet-stream"
    b64 = base64.b64encode(file_bytes).decode()
    return (
        f'<a href="data:{mime};base64,{b64}" download="{filename}" '
        f'style="text-decoration:none;font-weight:600;">{label}</a>'
    )


def rename_student(old_initials: str, new_initials: str) -> int:
    """Move every record from one student-initials folder to another.
    Returns the number of documents moved. Also used to merge folders
    (renaming onto existing initials combines them)."""
    try:
        client = _get_client()
        res = (
            client.table(TABLE)
            .update({"student_initials": new_initials.strip().upper()})
            .eq("student_initials", old_initials.strip().upper())
            .execute()
        )
        return len(res.data or [])
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not rename folder: {exc}")
        return 0


