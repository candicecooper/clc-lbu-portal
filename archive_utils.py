def connected_project() -> str:
    """The Supabase project URL the archive is actually connected to —
    for diagnostics, so SQL can be run in the matching project."""
    try:
        client = _get_client()
        return getattr(client, "supabase_url", None) or getattr(
            client, "rest_url", "unknown"
        )
    except Exception as exc:  # noqa: BLE001
        return f"not connected ({exc})"


def fetch_register(status: str | None = "active") -> list[dict]:
    """List students on the register. status='active', 'archived', or
    None for everyone. Sorted by initials."""
    try:
        client = _get_client()
        q = client.table(REGISTER_TABLE).select("*")
        if status:
            q = q.eq("status", status)
        res = q.order("initials").execute()
        return res.data or []
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not load student register: {exc}")
        return []


def register_student(
    *,
    initials: str,
    program: str | None = None,
    year_level: int | None = None,
    start_date=None,
    planned_exit_date=None,
    notes: str | None = None,
    created_by: str = "unknown",
) -> dict | None:
    """Add a student on arrival, identified by INITIALS + PROGRAM only
    (no names are stored anywhere). Refuses a duplicate of an ACTIVE
    student's initials so folders never collide."""
    try:
        client = _get_client()
        ini = re.sub(r"[^A-Za-z0-9]", "", (initials or "")).upper()
        if not ini or len(ini) < 2:
            st.error("Initials are required (at least 2 letters, e.g. JT).")
            return None

        active = fetch_register("active")
        if any(s["initials"] == ini for s in active):
            st.error(
                f"Initials **{ini}** are already used by an active student. "
                "Add a third letter to make them unique (e.g. first two "
                "letters of the surname)."
            )
            return None

        record = {
            "initials": ini,
            "program": program,
            "year_level": year_level,
            "notes": (notes or "").strip() or None,
            "created_by": created_by,
        }
        if start_date:
            record["start_date"] = str(start_date)
        if planned_exit_date:
            record["planned_exit_date"] = str(planned_exit_date)

        res = client.table(REGISTER_TABLE).insert(record).execute()
        created = res.data[0] if res.data else None
        if created:
            created["_behaviour_sync"] = sync_behaviour_create(
                ini, program, start_date, planned_exit_date, year_level
            )
        return created
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not add student: {exc}")
        return None


def set_student_status(record_id: str, status: str, exit_date=None) -> bool:
    """Archive ('archived' + exit date) or reactivate ('active') a student.
    Keeps the Behaviour Analysis tool's student list in step."""
    try:
        client = _get_client()
        payload = {"status": status}
        payload["exit_date"] = str(exit_date) if exit_date else None
        client.table(REGISTER_TABLE).update(payload).eq("id", record_id).execute()
        row = (
            client.table(REGISTER_TABLE).select("initials")
            .eq("id", record_id).execute()
        )
        ini = row.data[0]["initials"] if row.data else None
        if ini:
            if status == "archived":
                sync_behaviour_archive(ini, exit_date)
            else:
                sync_behaviour_reactivate(ini)
        return True
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not update student: {exc}")
        return False


def extend_student(record_id: str, old_exit_date, new_exit_date) -> bool:
    """Extend a student's placement: the planned exit date moves to the
    new date, the previous date is kept for the record, and the
    extension count increments."""
    try:
        client = _get_client()
        current = (
            client.table(REGISTER_TABLE)
            .select("extension_count")
            .eq("id", record_id)
            .execute()
        )
        n = (current.data[0].get("extension_count") or 0) if current.data else 0
        client.table(REGISTER_TABLE).update(
            {
                "planned_exit_date": str(new_exit_date),
                "previous_exit_date": str(old_exit_date) if old_exit_date else None,
                "extension_count": n + 1,
            }
        ).eq("id", record_id).execute()
        row = (
            client.table(REGISTER_TABLE).select("initials")
            .eq("id", record_id).execute()
        )
        if row.data:
            sync_behaviour_extend(row.data[0]["initials"], new_exit_date)
        return True
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not extend placement: {exc}")
        return False


def update_student_initials(record_id: str, old_initials: str, new_initials: str) -> int:
    """Change a student's initials on the register AND move their
    document-archive folder to match. Returns docs moved."""
    try:
        client = _get_client()
        client.table(REGISTER_TABLE).update(
            {"initials": new_initials.strip().upper()}
        ).eq("id", record_id).execute()
        sync_behaviour_initials(old_initials, new_initials)
        return rename_student(old_initials, new_initials)
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not update initials: {exc}")
        return 0


def import_from_behaviour(created_by: str = "unknown") -> tuple[int, int, list]:
    """One-click import: create register entries for every ACTIVE student
    in the Behaviour Analysis tool who isn't on the register yet.
    Returns (imported, skipped_existing, problems)."""
    imported, skipped, problems = 0, 0, []
    try:
        client = _get_client()
        beh = (
            client.table(BEHAVIOUR_STUDENTS_TABLE)
            .select("first_name, last_name, name, program, year_level, "
                    "placement_start, placement_end, enrolled_date, archived")
            .execute()
        ).data or []
        existing = {s["initials"] for s in fetch_register(None)}

        for b in beh:
            if b.get("archived"):
                continue
            raw = f"{b.get('first_name') or ''}{b.get('last_name') or ''}" or (b.get("name") or "")
            ini = re.sub(r"[^A-Za-z0-9]", "", raw).upper()
            if len(ini) < 2:
                problems.append(
                    f"{b.get('name') or raw or '?'} — initials too short to import"
                )
                continue
            if ini in existing:
                skipped += 1
                continue
            record = {
                "initials": ini,
                "program": b.get("program"),
                "year_level": b.get("year_level"),
                "notes": None,
                "created_by": created_by,
            }
            start = b.get("placement_start") or b.get("enrolled_date")
            if start:
                record["start_date"] = str(start)[:10]
            if b.get("placement_end"):
                record["planned_exit_date"] = str(b["placement_end"])[:10]
            client.table(REGISTER_TABLE).insert(record).execute()
            existing.add(ini)
            imported += 1
    except Exception as exc:  # noqa: BLE001
        st.error(f"Import failed: {exc}")
    return imported, skipped, problems


def import_from_smartar(created_by: str = "unknown") -> tuple[int, int, list]:
    """One-click import: create register entries (and thus archive folders)
    for every ACTIVE student in the SMARTAR Goal tool who isn't on the
    register yet. Returns (imported, skipped_existing, problems)."""
    imported, skipped, problems = 0, 0, []
    try:
        client = _get_client()
        rows = (
            client.table("smartar_students")
            .select("student_name, active")
            .eq("active", True)
            .execute()
        ).data or []
        existing = {s["initials"] for s in fetch_register(None)}

        for r in rows:
            raw = (r.get("student_name") or "").strip()
            clean = re.sub(r"[^A-Za-z0-9]", "", raw).upper()
            if 2 <= len(clean) <= 4:
                ini = clean                      # already initials-style
            else:
                ini = initials_from_name(raw)    # full name -> initials
            if not ini or len(re.sub(r"[^A-Za-z0-9]", "", ini)) < 2:
                problems.append(f"'{raw}' — could not derive usable initials")
                continue
            ini = re.sub(r"[^A-Za-z0-9]", "", ini).upper()
            if ini in existing:
                skipped += 1
                continue
            client.table(REGISTER_TABLE).insert(
                {"initials": ini, "created_by": created_by}
            ).execute()
            existing.add(ini)
            imported += 1
    except Exception as exc:  # noqa: BLE001
        st.error(f"SMARTAR import failed: {exc}")
    return imported, skipped, problems


def update_student_details(record_id: str, program=None, year_level=None) -> bool:
    """Update a register student's program / year level."""
    try:
        client = _get_client()
        client.table(REGISTER_TABLE).update(
            {"program": program, "year_level": year_level}
        ).eq("id", record_id).execute()
        return True
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not update details: {exc}")
        return False


def delete_register_entry(record_id: str) -> bool:
    """TRUE delete of a register row — for bad imports/duplicates only.
    (Archiving a student is the normal end-of-placement action.)"""
    try:
        client = _get_client()
        client.table(REGISTER_TABLE).delete().eq("id", record_id).execute()
        return True
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not remove entry: {exc}")
        return False


def merge_register_student(source_id: str, source_initials: str,
                           target_initials: str) -> int:
    """Merge a duplicate: move all of source's archived documents into
    the target's folder, then delete the source register row.
    Returns documents moved."""
    moved = rename_student(source_initials, target_initials)
    delete_register_entry(source_id)
    return moved


def register_program_map() -> dict:
    """{initials: program} for every registered student (active and
    archived) — used by the Document Archive to display the program
    next to each folder."""
    return {s["initials"]: (s.get("program") or "") for s in fetch_register(None)}
