"""
archive_utils.py — Shared document archive module for the CLC-LBU Portal
=========================================================================

Central archive for documents generated by portal tools (PDP Builder,
Behaviour Support Tool, Safety & Risk Plan Builder, etc.).

Any tool can archive a document at the point of export with one call:

    from archive_utils import archive_document

    archive_document(
        source_tool="PDP Builder",
        doc_type="PDP",
        title=f"PDP — {staff_name} — 2026",
        file_bytes=docx_bytes,
        filename=f"pdp_{staff_name.lower().replace(' ', '_')}_2026.docx",
        confidential=True,
        created_by=st.session_state.get("user_email", "unknown"),
    )

Storage layout (Supabase Storage, private bucket "document-archive"):
    {year}/{term}/{source_tool_slug}/{uuid8}_{filename}

Privacy: student-linked documents store INITIALS ONLY in metadata,
consistent with the Communication Log approach. Never pass full student
names into title, tags, or student_initials.
"""

