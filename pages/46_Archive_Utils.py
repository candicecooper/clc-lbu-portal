# ---------------------------------------------------------------------------
# Supabase client
# ---------------------------------------------------------------------------

@st.cache_resource
def _get_client():
    """Return a Supabase client.

    Tries the portal's shared database module first; falls back to
    creating a client directly from st.secrets.

    >>> ADJUST the import below if your helper in database.py has a
    >>> different name (e.g. get_client / init_supabase).
    """
    try:
        from database import get_supabase_client  # noqa: WPS433
        return get_supabase_client()
    except Exception:
        from supabase import create_client
        return create_client(
            st.secrets["SUPABASE_URL"],
            st.secrets["SUPABASE_KEY"],
        )


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _slugify(text: str) -> str:
    text = re.sub(r"[^A-Za-z0-9]+", "-", text.strip().lower())
    return text.strip("-") or "misc"


def _current_term_and_year():
    """Best-guess SA school term from today's date (adjust if needed)."""
    now = datetime.now()
    m = now.month
    if m <= 4:
        term = "Term 1"
    elif m <= 7:
        term = "Term 2"
    elif m <= 9:
        term = "Term 3"
    else:
        term = "Term 4"
    return term, now.year


def _safe_filename(filename: str) -> str:
    name = re.sub(r"[^A-Za-z0-9._-]+", "_", filename.strip())
    return name or "document"


