def set_cell_shading(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def set_col_widths(table, widths_cm):
    table.autofit = False
    for row in table.rows:
        for idx, cell in enumerate(row.cells):
            cell.width = Cm(widths_cm[idx])
    for idx, col in enumerate(table.columns):
        col.width = Cm(widths_cm[idx])


def add_heading(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(4)
    run = p.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = NAVY
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "2")
    bottom.set(qn("w:color"), NAVY_HEX)
    pBdr.append(bottom)
    pPr.append(pBdr)
    return p


def add_field_line(doc, label, value):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    r1 = p.add_run(f"{label}: ")
    r1.bold = True
    r1.font.color.rgb = NAVY
    r1.font.size = Pt(10.5)
    r2 = p.add_run(value or "")
    r2.font.size = Pt(10.5)
    return p


def add_plain(doc, text):
    lines = (text or "").split("\n") or [""]
    first_p = None
    for line in lines:
        p = doc.add_paragraph(line)
        p.paragraph_format.space_after = Pt(4)
        for r in p.runs:
            r.font.size = Pt(10.5)
        if first_p is None:
            first_p = p
    return first_p


def fill_cell_multiline(cell, text, size=10, bold=False, color=None, align_center=False):
    """Write text into a table cell, splitting on '\\n' so each line
    becomes its own paragraph — matching the official ABC-H template,
    where each distinct action/name/quote is its own paragraph rather
    than one run-on block of prose."""
    lines = (text or "").split("\n") or [""]
    first = True
    for line in lines:
        p = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        if align_center:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(line)
        run.font.size = Pt(size)
        run.bold = bold
        if color:
            run.font.color.rgb = color
    return cell


def add_details_grid(doc, pairs, col_widths_cm=(3.2, 8.7, 3.2, 8.7)):
    rows = [pairs[i:i + 2] for i in range(0, len(pairs), 2)]
    table = doc.add_table(rows=len(rows), cols=4)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    for r_idx, pair_row in enumerate(rows):
        cells = table.rows[r_idx].cells
        for i in range(2):
            if i < len(pair_row):
                label, value = pair_row[i]
            else:
                label, value = "", ""
            lbl_cell, val_cell = cells[i * 2], cells[i * 2 + 1]
            fill_cell_multiline(lbl_cell, label, size=10, bold=True, color=NAVY)
            set_cell_shading(lbl_cell, GREY_HEX)
            fill_cell_multiline(val_cell, value, size=10)
    set_col_widths(table, col_widths_cm)
    return table


PHASE_COLS = ["PHASE", "LOCATION", "CONTEXT / ANTECEDENT", "TIME", "BEHAVIOUR (STUDENT)", "CONSEQUENCE (STAFF / OTHERS)"]
PHASE_WIDTHS_CM = [1.4, 3.6, 6.0, 1.9, 5.8, 6.0]


def add_phase_table(doc, phases):
    table = doc.add_table(rows=1, cols=len(PHASE_COLS))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr_cells = table.rows[0].cells
    for i, col_name in enumerate(PHASE_COLS):
        hdr_cells[i].text = ""
        p = hdr_cells[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(col_name)
        run.bold = True
        run.font.size = Pt(9)
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        set_cell_shading(hdr_cells[i], NAVY_HEX)

    for idx, phase in enumerate(phases):
        row_cells = table.add_row().cells
        values = [
            phase.get("number", str(idx + 1)),
            phase.get("Location", ""),
            phase.get("Context", ""),
            phase.get("Time", ""),
            phase.get("Behaviour", ""),
            phase.get("Consequence", ""),
        ]
        for i, val in enumerate(values):
            fill_cell_multiline(
                row_cells[i], val, size=9, bold=(i == 0), align_center=(i == 0)
            )
            if idx % 2 == 1:
                set_cell_shading(row_cells[i], LIGHT_HEX)
    set_col_widths(table, PHASE_WIDTHS_CM)
    return table


def build_docx(parsed):
    doc = Document()
    section = doc.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = section.page_height, section.page_width
    section.left_margin = section.right_margin = Cm(1.3)
    section.top_margin = section.bottom_margin = Cm(1.3)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = title.add_run(f"ABCH – {parsed['student'].get('Name') or '[STUDENT NAME]'}")
    r.bold = True
    r.font.size = Pt(20)
    r.font.color.rgb = NAVY

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = sub.add_run("Cowandilla Learning Centre – Critical Incident Report (ABC-H)")
    r2.italic = True
    r2.font.size = Pt(10)
    r2.font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    add_heading(doc, "Student Details")
    s = parsed["student"]
    add_details_grid(doc, [
        ("Name", s.get("Name", "")), ("DOB", s.get("DOB", "")),
        ("EDSAS ID", s.get("EDSAS ID", "")), ("Program", s.get("Program", "")),
        ("Year Level", s.get("Year Level", "")), ("Home School", s.get("Home School", "")),
        ("Witnesses", s.get("Witnesses", "")), ("Other students involved", s.get("Other students involved", "")),
    ])

    add_heading(doc, "Incident Details & Reporting Staff")
    inc = parsed["incident"]
    add_details_grid(doc, [
        ("Incident Date", inc.get("Incident Date", "")), ("Incident Time", inc.get("Incident Time", "")),
        ("Incident End Time", inc.get("Incident End Time", "")), ("Location(s)", inc.get("Location", "")),
        ("Reporting Staff", inc.get("Reporting Staff", "")), ("", ""),
    ])

    add_heading(doc, "Incident Timeline – ABC-H (one row per phase of the same incident)")
    add_phase_table(doc, parsed["phases"])

    if parsed.get("harm"):
        add_heading(doc, "Harm / Outcomes")
        add_plain(doc, parsed["harm"])

    ed = parsed.get("ed155", {})
    if ed:
        add_heading(doc, "ED155")
        for k in ["ED155 required", "ED155 completed", "ED155 number"]:
            if ed.get(k):
                add_field_line(doc, k, ed[k])

    es = parsed.get("emergency", {})
    if es:
        add_heading(doc, "Emergency Services")
        if isinstance(es, dict):
            for k, v in es.items():
                if v:
                    add_field_line(doc, k, v)
        else:
            add_plain(doc, es)

    if parsed.get("staff_responses"):
        add_heading(doc, "Staff Responses")
        add_plain(doc, parsed["staff_responses"])

    hyp_input = parsed.get("hypothesis_input", {})
    if hyp_input:
        add_heading(doc, "Hypothesis Input (Staff)")
        if hyp_input.get("Function"):
            add_field_line(doc, "Function", hyp_input["Function"])
        for k, v in hyp_input.items():
            if k != "Function" and v:
                add_field_line(doc, k, v)

    notif = parsed.get("notifications", {})
    if notif:
        add_heading(doc, "Notifications")
        for k in ["Parent/Carer informed", "Method", "Informed by", "Time informed", "Others notified"]:
            if notif.get(k):
                add_field_line(doc, k, notif[k])

    if parsed.get("declaration"):
        add_heading(doc, "Staff Declaration")
        add_plain(doc, "I confirm that the information I have entered is correct.")
        d = parsed["declaration"]
        if d.get("Signed"):
            add_field_line(doc, "Signed", d["Signed"])
        if d.get("Report completed on"):
            add_field_line(doc, "Report completed on", d["Report completed on"])

    hyp = parsed.get("hypothesis", {})
    if hyp:
        add_heading(doc, "AI-Generated Hypothesis")
        for k in ["Pattern", "Function", "Why behaviour continued", "Key insight"]:
            if hyp.get(k):
                add_field_line(doc, k, hyp[k])

    if parsed.get("irms"):
        add_heading(doc, "Incident Summary (IRMS)")
        add_plain(doc, parsed["irms"])

    tag = parsed.get("tagging", {})
    if tag:
        add_heading(doc, "Incident Tagging")
        for k in ["Trigger Type", "Behaviour Type", "Function", "Escalation Level"]:
            if tag.get(k):
                add_field_line(doc, k, tag[k])

    add_heading(doc, "Leadership Signature")
    add_plain(doc, "This section is completed by leadership after reviewing the incident — left blank at the point of submission.")
    add_field_line(doc, "Reviewed by (Leadership name)", "_" * 35)
    add_field_line(doc, "Signature", "_" * 35)
    add_field_line(doc, "Date reviewed", "_" * 25)
    add_field_line(doc, "Comments / follow-up actions", "")
    doc.add_paragraph("_" * 90)
    doc.add_paragraph("_" * 90)

    bio = io.BytesIO()
    doc.save(bio)
    bio.seek(0)
    return bio


