# Reading an edited .docx back in (for the "recreate after manual edits"
# feature) — walk the document in true order, reconstruct it as
# EdChat-style plain text, then run it through the same parse_report()
# used for freshly pasted reports. This avoids maintaining a second,
# separate parser for the table-based Word layout.
# ----------------------------------------------------------------------

_KNOWN_HEADINGS = [
    "STUDENT DETAILS", "INCIDENT DETAILS & REPORTING STAFF",
    "INCIDENT TIMELINE", "HARM / OUTCOMES", "ED155", "EMERGENCY SERVICES",
    "STAFF RESPONSES", "HYPOTHESIS INPUT (STAFF)", "NOTIFICATIONS",
    "STAFF DECLARATION", "AI-GENERATED HYPOTHESIS", "INCIDENT SUMMARY (IRMS)",
    "INCIDENT TAGGING", "LEADERSHIP SIGNATURE",
]
_HEADING_TO_SECTION = {
    "STUDENT DETAILS": "STUDENT DETAILS",
    "INCIDENT DETAILS & REPORTING STAFF": "INCIDENT DETAILS",
    "INCIDENT TIMELINE": "INCIDENT TIMELINE – ABC-H",
    "HARM / OUTCOMES": "HARM / OUTCOMES",
    "ED155": "ED155",
    "EMERGENCY SERVICES": "EMERGENCY SERVICES",
    "STAFF RESPONSES": "STAFF RESPONSES",
    "HYPOTHESIS INPUT (STAFF)": "HYPOTHESIS INPUT",
    "NOTIFICATIONS": "NOTIFICATIONS",
    "STAFF DECLARATION": "STAFF DECLARATION",
    "AI-GENERATED HYPOTHESIS": "AI-GENERATED HYPOTHESIS",
    "INCIDENT SUMMARY (IRMS)": "INCIDENT SUMMARY (IRMS)",
    "INCIDENT TAGGING": "INCIDENT TAGGING",
}


def _iter_block_items(doc):
    """Yield each Paragraph/Table in the document in true reading order
    (python-docx doesn't expose this directly — doc.paragraphs and
    doc.tables are each in order internally, but interleaved order
    between the two is lost unless you walk the underlying XML)."""
    parent_elm = doc.element.body
    for child in parent_elm.iterchildren():
        if child.tag == _qn("w:p"):
            yield DocxParagraph(child, doc)
        elif child.tag == _qn("w:tbl"):
            yield DocxTable(child, doc)


def _cell_text(cell):
    return "\n".join(p.text.strip() for p in cell.paragraphs if p.text.strip())


def _details_grid_to_lines(table):
    """A student/incident details grid is 4 columns: label, value, label,
    value, one or two pairs per row. Reconstruct as 'Label: value' lines."""
    lines = []
    for row in table.rows:
        cells = row.cells
        for i in (0, 2):
            if i + 1 >= len(cells):
                continue
            label = _cell_text(cells[i])
            value = _cell_text(cells[i + 1])
            if label:
                lines.append(f"{label}: {value}")
    return lines


def _phase_table_to_lines(table):
    """The phase table's header row is PHASE/LOCATION/CONTEXT.../TIME/
    BEHAVIOUR/CONSEQUENCE. Reconstruct each data row as a PHASE block."""
    lines = []
    rows = table.rows
    if not rows:
        return lines
    header = [c.text.strip().upper() for c in rows[0].cells]
    for row in rows[1:]:
        cells = row.cells
        vals = {header[i]: _cell_text(cells[i]) for i in range(min(len(header), len(cells)))}
        num = vals.get("PHASE", "").strip() or str(len(lines) // 6 + 1)
        lines.append(f"PHASE {num}")
        lines.append(f"Location: {vals.get('LOCATION', '')}")
        lines.append(f"Context / Antecedent: {vals.get('CONTEXT / ANTECEDENT', vals.get('CONTEXT', ''))}")
        lines.append(f"Time: {vals.get('TIME', '')}")
        lines.append(f"Behaviour (Student): {vals.get('BEHAVIOUR (STUDENT)', '')}")
        lines.append(f"Consequence (Staff / Others): {vals.get('CONSEQUENCE (STAFF / OTHERS)', '')}")
        lines.append("")
    return lines


def docx_to_report_text(file_bytes):
    """Read an uploaded, possibly hand-edited, ABCH Word document and
    reconstruct it as EdChat-style plain text so it can be run back
    through parse_report(). Stops at LEADERSHIP SIGNATURE — that section
    is never re-imported, since it's leadership's to complete, not staff's
    to edit."""
    doc = Document(io.BytesIO(file_bytes))
    out_lines = []
    current_heading = None
    table_index = 0  # 0 = student grid, 1 = incident grid, 2 = phase table, then done with tables
    stop = False

    for block in _iter_block_items(doc):
        if stop:
            break
        if isinstance(block, DocxTable):
            if table_index == 0:
                out_lines.extend(_details_grid_to_lines(block))
            elif table_index == 1:
                out_lines.extend(_details_grid_to_lines(block))
            elif table_index == 2:
                out_lines.extend(_phase_table_to_lines(block))
            table_index += 1
            continue

        text = block.text.strip()
        if not text:
            continue
        upper = text.upper()
        matched_heading = next((h for h in _KNOWN_HEADINGS if upper == h or upper.startswith(h)), None)
        if matched_heading:
            if matched_heading == "LEADERSHIP SIGNATURE":
                stop = True
                break
            current_heading = _HEADING_TO_SECTION[matched_heading]
            out_lines.append(current_heading)
            continue
        # Skip the title line and the italic subtitle under it.
        if text.startswith("ABCH") or "Cowandilla Learning Centre" in text:
            continue
        out_lines.append(text)

    return "\n".join(out_lines)


GROQ_MODEL_CHAIN = ["openai/gpt-oss-120b", "qwen/qwen3.6-27b", "llama-3.3-70b-versatile"]


def _make_groq_client():
    """Groq client creation has hit a recurring portal-wide issue: a stale
    cached `groq` wheel + newer `httpx` raises
    `Client.__init__() got an unexpected keyword argument 'proxies'`.
    Fall back to an explicitly-built httpx.Client() if that happens."""
    try:
        return Groq()
    except TypeError as e:
        if "proxies" not in str(e):
            raise
        import httpx
        return Groq(http_client=httpx.Client())


def _groq_chat_call(client, model, prompt, max_tokens=1000):
    """One Groq call, with the Qwen-specific thinking-token suppression and
    a self-healing retry that halves max_tokens on a 'too large' error
    instead of repeating the identical oversized request."""
    kwargs = dict(
        model=model,
        max_tokens=max_tokens,
        temperature=0.2,
        messages=[{"role": "user", "content": prompt}],
    )
    if model.startswith("qwen/"):
        kwargs["reasoning_effort"] = "none"
    try:
        response = client.chat.completions.create(**kwargs)
    except Exception as e:
        if "too large" in str(e).lower() and max_tokens > 500:
            kwargs["max_tokens"] = max_tokens // 2
            response = client.chat.completions.create(**kwargs)
        else:
            raise
    return response.choices[0].message.content


def rejig_hypothesis_with_ai(parsed, original_hypothesis=None):
    """Call Groq to re-derive the AI-Generated Hypothesis / IRMS summary
    / tagging from the (possibly edited) phases, and say plainly whether
    the edits actually changed the picture. Returns (updated_dict, note)
    or (None, error_message) if the call couldn't be made. Uses Groq
    (with the portal's confirmed-working model fallback chain) rather
    than a paid API, since this tool is used by many staff."""
    if not _GROQ_AVAILABLE:
        return None, "The groq package isn't installed in this environment."

    try:
        client = _make_groq_client()
    except Exception as e:
        return None, f"Couldn't set up the Groq client ({e}). Check GROQ_API_KEY is configured."

    phase_text = "\n\n".join(
        f"Phase {p.get('number')}\nLocation: {p.get('Location','')}\n"
        f"Context/Antecedent: {p.get('Context','')}\nTime: {p.get('Time','')}\n"
        f"Behaviour: {p.get('Behaviour','')}\nConsequence: {p.get('Consequence','')}"
        for p in parsed.get("phases", [])
    )
    student_name = parsed.get("student", {}).get("Name", "the student")

    original_block = ""
    if original_hypothesis:
        original_block = (
            "\n\nORIGINAL HYPOTHESIS (before edits), for comparison only — do not just repeat it, "
            "re-derive from the edited phases below and say whether it still holds:\n"
            + "\n".join(f"{k}: {v}" for k, v in original_hypothesis.items())
        )

    prompt = f"""You are re-deriving the behavioural hypothesis for a CLC-LBU ABC-H critical incident report, after a staff member has hand-edited the incident phases. Base your answer ONLY on the phase text below — do not invent details.

STUDENT: {student_name}

EDITED PHASES:
{phase_text}
{original_block}

Produce exactly this structure, plain text, no markdown:

IMPACT: [state in one line whether the edits materially changed the hypothesis compared to before — "No material change" or a one-sentence description of what changed and why]

PATTERN: [1-2 sentences]
FUNCTION: [Get or Avoid, plus what specifically — 1-2 sentences]
WHY BEHAVIOUR CONTINUED: [1-2 sentences]
KEY INSIGHT: [1-2 sentences]

IRMS SUMMARY: [3-5 sentences, suitable for the Incident Summary (IRMS) section]

TRIGGER TYPE: [short phrase]
BEHAVIOUR TYPE: [short phrase]
TAGGING FUNCTION: [short phrase]
ESCALATION LEVEL: [one of: Anxiety / Defensive / Risk Behaviour / Tension Reduction — or a range like "Defensive to Risk Behaviour" — using CPI's Crisis Development Model, based on the highest level reached across the phases]"""

    text = None
    last_error = None
    for model in GROQ_MODEL_CHAIN:
        try:
            text = _groq_chat_call(client, model, prompt, max_tokens=1000)
            break
        except Exception as e:
            last_error = e
            continue

    if text is None:
        return None, f"Groq API call failed on all models: {last_error}"

    def _extract(label):
        m = re.search(rf"^{re.escape(label)}:\s*(.*)$", text, re.MULTILINE)
        return m.group(1).strip() if m else ""

    impact_note = _extract("IMPACT")
    updated = {
        "hypothesis": {
            "Pattern": _extract("PATTERN"),
            "Function": _extract("FUNCTION"),
            "Why behaviour continued": _extract("WHY BEHAVIOUR CONTINUED"),
            "Key insight": _extract("KEY INSIGHT"),
        },
        "irms": _extract("IRMS SUMMARY"),
        "tagging": {
            "Trigger Type": _extract("TRIGGER TYPE"),
            "Behaviour Type": _extract("BEHAVIOUR TYPE"),
            "Function": _extract("TAGGING FUNCTION"),
            "Escalation Level": _extract("ESCALATION LEVEL"),
        },
    }
    return updated, impact_note


