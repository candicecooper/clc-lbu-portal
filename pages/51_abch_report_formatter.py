"""
ABCH Report Formatter
----------------------
Paste the plain-text report generated by the EdChat C.I. Bot and this tool
reformats it into the landscape Word (.docx) layout, with one incident
"phase" per row (Location / Context / Time / Antecedent / Behaviour /
Consequence) running across the page.

PRIVACY: This tool does NOT save, store, log, or transmit anything you paste.
Everything happens in memory for this browser session only, and is cleared
when you close or refresh the page. No Supabase table, no database write.
Student-identifiable text should only ever exist in EdChat (approved system
of record) and, briefly, on your own screen here while you generate the
Word file to save into the student's file / EMS.

Drop this file into the portal's `pages/` folder alongside the other
numbered tools (e.g. as 47_ABCH_Report_Formatter.py).
"""

